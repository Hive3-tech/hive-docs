// Writes public/_redirects from src/content/redirects.ts. Run with `npm run redirects` after editing it.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { contentDir, root } from "./lib/content.mjs";

const { legacyRedirects, sectionRootRedirects } = await import(pathToFileURL(join(contentDir, "redirects.ts")).href);

export function redirectsFile() {
  const rows = [...Object.entries(sectionRootRedirects), ...Object.entries(legacyRedirects)];
  const width = Math.max(...rows.map(([from]) => from.length)) + 2;
  return [
    "# Generated by `npm run redirects` from src/content/redirects.ts. Do not edit by hand.",
    ...rows.map(([from, to]) => `${from.padEnd(width)}${to}  301`),
    "",
    "# Unknown URLs get the prerendered 404 page with a 404 status.",
    `${"/*".padEnd(width)}/404.html  404`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(join(root, "public/_redirects"), redirectsFile());
  console.log("Wrote public/_redirects");
}
